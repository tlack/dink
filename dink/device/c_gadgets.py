"""Write the example gadgets as a C header for the test firmware (esp32/firmware/main/), with
each request's LLM label and the PyTorch harness's answer, so the board's answers can be
compared on the spot.

  uv run python -m dink.device.c_gadgets models/dink-v16 --out esp32/firmware/main/gadgets.h
"""
import argparse
import json
from pathlib import Path

from ..harness import decide
from ..play import load_model


def cstr(s):
    return json.dumps(s)                     # a valid C string literal for these ASCII texts


def fl(v):
    return f"{float(v)!r}f"                  # 1200 -> 1200.0f (an integer literal can't take f)


def label(g, action, value):
    if action in (None, "none"):
        return "(nothing)"
    a = next(x for x in g["actions"] if x["name"] == action)
    return f"{action}()" if a["lo"] is None else f"{action}={value:g}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    ap.add_argument("--gadgets", default="examples/gadgets")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    model = load_model(a.run, "cpu")
    out = ["// Generated by dink-model's dink/device/c_gadgets.py from examples/gadgets: do not edit.",
           "// Gadgets an LLM invented, with labeled requests; `torch` is the PyTorch harness's answer.",
           "#pragma once", '#include "dink.h"', "",
           "typedef struct { const char *say, *kind, *llm, *torch; } demo_request_t;",
           "typedef struct { const char *setting; dink_field_t *fields; int n_fields; const dink_action_t *actions;",
           "                 int n_actions; const demo_request_t *requests; int n_requests; } demo_gadget_t;", ""]
    names = []
    for f in sorted(Path(a.gadgets).glob("*.json")):
        g, k = json.loads(f.read_text()), f.stem
        names.append(k)
        out.append(f"static dink_field_t {k}_fields[] = {{")
        out += [f"    {{{cstr(x['name'])}, {fl(x['value'])}, {fl(x['lo'])}, {fl(x['hi'])}}}," for x in g["state"]]
        out.append("};")
        out.append(f"static const dink_action_t {k}_actions[] = {{")
        for x in g["actions"]:
            if x["lo"] is None:
                out.append(f"    {{{cstr(x['name'])}, 0, 0, 0, NULL}},")
            else:
                sets = cstr(x["sets"]) if x.get("sets") else "NULL"
                out.append(f"    {{{cstr(x['name'])}, {fl(x['lo'])}, {fl(x['hi'])}, 1, {sets}}},")
        out.append("};")
        out.append(f"static const demo_request_t {k}_requests[] = {{")
        for u in g["utterances"]:
            if u["source"] != "request" or u.get("limit"):   # limit requests need a modified state
                continue
            r = decide(model, g, u["say"])
            t = "(nothing)" if r["pick"] is None else (f"{r['pick'].name}={r['pick'].value:g}" if r["pick"].arg
                                                       else f"{r['pick'].name}()")
            out.append(f"    {{{cstr(u['say'])}, {cstr(u['kind'])}, {cstr(label(g, u['action'], u.get('value')))}, {cstr(t)}}},")
        out.append("};")
        out.append("")
    out.append("static const demo_gadget_t demo_gadgets[] = {")
    for k in names:
        g = json.loads((Path(a.gadgets) / f"{k}.json").read_text())
        out.append(f"    {{{cstr(g['setting'])}, {k}_fields, sizeof {k}_fields / sizeof *{k}_fields, {k}_actions,")
        out.append(f"     sizeof {k}_actions / sizeof *{k}_actions, {k}_requests, sizeof {k}_requests / sizeof *{k}_requests}},")
    out.append("};")
    out.append(f"#define N_DEMO_GADGETS {len(names)}")
    Path(a.out).write_text("\n".join(out) + "\n")
    print(f"-> {a.out}: {len(names)} gadgets")


if __name__ == "__main__":
    main()
